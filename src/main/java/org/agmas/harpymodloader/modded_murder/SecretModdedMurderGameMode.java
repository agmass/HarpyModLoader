public class SecretModdedMurderGameMode extends ModdedMurderGameMode {

    public SecretModdedMurderGameMode(Identifier identifier) {
        super(identifier);
    }

    private static int assignRolesAndGetKillerCount(@NotNull ServerWorld world, @NotNull List<ServerPlayerEntity> players, GameWorldComponent gameComponent) {
        for(ServerPlayerEntity player : players) {
            gameComponent.addRole(player, WatheRoles.KILLER);
            ((PlayerShopComponent)PlayerShopComponent.KEY.get(player)).setBalance(100);
        }

        return (int)Math.floor((double)players.size() / (double)gameComponent.getKillerDividend());
    }

    public void initializeGame(ServerWorld serverWorld, GameWorldComponent gameWorldComponent, List<ServerPlayerEntity> players) {
        int killerCount = assignRolesAndGetKillerCount(serverWorld, players, gameWorldComponent);

        Harpymodloader.refreshRoles();

        assignKillerReplacingRoles(99999,serverWorld,gameWorldComponent,players);

        int modifierRoleCount = killerCount * HarpyModLoaderConfig.HANDLER.instance().modifierMultiplier;
        assignModifiers(modifierRoleCount, serverWorld,gameWorldComponent,players);

        for(ServerPlayerEntity player : players) {
            if (Harpymodloader.VANNILA_ROLES.contains(gameWorldComponent.getRole(player))) {
                ServerPlayNetworking.send(player, new AnnounceWelcomePayload(RoleAnnouncementTexts.ROLE_ANNOUNCEMENT_TEXTS.indexOf(gameWorldComponent.isRole(player, WatheRoles.KILLER) ? RoleAnnouncementTexts.KILLER : (gameWorldComponent.isRole(player, WatheRoles.VIGILANTE) ? RoleAnnouncementTexts.VIGILANTE : RoleAnnouncementTexts.CIVILIAN)),  killerCount, players.size() - killerCount));
            } else {
                ServerPlayNetworking.send(player, new AnnounceWelcomePayload(RoleAnnouncementTexts.ROLE_ANNOUNCEMENT_TEXTS.indexOf(Harpymodloader.autogeneratedAnnouncements.get(gameWorldComponent.getRole(player))),  killerCount, players.size() - killerCount));
            }
        }


        Harpymodloader.FORCED_MODDED_ROLE.clear();
        Harpymodloader.FORCED_MODDED_ROLE_FLIP.clear();

        Harpymodloader.FORCED_MODDED_MODIFIER.clear();
    }

    public void tickServerGameLoop(ServerWorld serverWorld, GameWorldComponent gameWorldComponent) {
        GameFunctions.WinStatus winStatus = GameFunctions.WinStatus.NONE;
        if (!((GameTimeComponent)GameTimeComponent.KEY.get(serverWorld)).hasTime()) {
            winStatus = GameFunctions.WinStatus.TIME;
        }

        int playersLeft = 0;
        PlayerEntity lastPlayer = null;

        for(PlayerEntity player : serverWorld.getPlayers()) {
            if (GameFunctions.isPlayerAliveAndSurvival(player)) {
                ++playersLeft;
                lastPlayer = player;
            }
        }

        if (playersLeft <= 0) {
            GameFunctions.stopGame(serverWorld);
        }

        if (playersLeft == 1) {
            gameWorldComponent.setLooseEndWinner(lastPlayer.getUuid());
            winStatus = GameFunctions.WinStatus.LOOSE_END;
        }

        if (winStatus != GameFunctions.WinStatus.NONE && gameWorldComponent.getGameStatus() == GameWorldComponent.GameStatus.ACTIVE) {
            ((GameRoundEndComponent)GameRoundEndComponent.KEY.get(serverWorld)).setRoundEndData(serverWorld.getPlayers(), winStatus);
            GameFunctions.stopGame(serverWorld);
        }

    }
}
